const collection = JSON.parse(await readFile(collectionPath, "utf8"));
const selectedIcons = Object.fromEntries(
  iconNames.map((name) => {
    const icon = collection.icons[name];

    if (!icon) {
      throw new Error(`VSCode icon is missing from the collection: ${name}`);
    }

    return [
      name,
      {
        body: icon.body,
        width: icon.width ?? collection.width ?? 32,
        height: icon.height ?? collection.height ?? 32,
      },
    ];
  }),
);
const output = `// Generated by scripts/generate-file-icons.mjs. Do not edit manually.
export const FILE_ICON_DATA = ${JSON.stringify(selectedIcons, null, 2)} as const;

export type FileIconName = keyof typeof FILE_ICON_DATA;
`;

await writeFile(outputPath, output);
console.log(`Generated ${iconNames.length} file icons`);
